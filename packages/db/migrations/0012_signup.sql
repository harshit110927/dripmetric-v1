-- 0012_signup.sql — M12. Guarding the email-only instant project (brief §9).
--
-- "limit creation per IP and filter disposable emails."
--
-- The flow has no password and no payment, so this table is the only thing between it
-- and someone minting ten thousand projects.

CREATE TABLE signup_attempts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  /*
   * The IP, hashed.
   *
   * It is only ever counted, never looked up, so a hash does the whole job — and an
   * IP address is personal data in the EU, which makes keeping the plain value a
   * liability for nothing in return. Null when there is no forwarded address to read.
   */
  ip_hash     bytea,

  /*
   * The DOMAIN, not the address.
   *
   * Enough to see an abuse pattern, and not a list of everyone who tried the product
   * and changed their mind. Those people did not become customers and we should not
   * be holding their addresses.
   */
  email_domain text,

  created_project boolean NOT NULL DEFAULT false,
  reason      text NOT NULL DEFAULT 'ok',
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- The guard's own query: how many projects from this IP in the last day.
CREATE INDEX signup_attempts_ip_idx ON signup_attempts (ip_hash, created_at DESC)
  WHERE created_project;

-- Not tenant data: an attempt has no project yet, which is the point of it. So no
-- RLS policy — nothing in the request path reads this except the signup guard, which
-- runs through `withoutProject`.
REVOKE ALL ON signup_attempts FROM PUBLIC;
GRANT SELECT, INSERT ON signup_attempts TO dripmetric_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO dripmetric_app;
