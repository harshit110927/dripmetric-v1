-- 0010_health.sql — M11. Tracking health and retention (brief §9, §10).
--
-- "Silent breakage is the fastest way to lose a founder's trust in the numbers, so
-- watch the tracking itself."
--
-- Three things live here: the history a shape-drift check needs, the findings
-- themselves, and a dedupe key so a tracking alert can reach the feed without the
-- leak instance the feed was built around.

-- ---------------------------------------------------------------------------
-- Shape drift needs a BEFORE, and the dictionary only had an after.
--
-- `event_name_properties`' primary key is (project, name, property) with one
-- `value_type`, so a property that changes from a number to a string simply
-- overwrites the old type and the change becomes invisible. Keeping the previous
-- type and when it changed is the smallest thing that makes the check possible.
-- ---------------------------------------------------------------------------
ALTER TABLE event_name_properties
  ADD COLUMN prior_value_type text,
  ADD COLUMN type_changed_at  timestamptz,
  -- How many events carried the old type. A property seen twice as a number and then
  -- settling as a string is a founder fixing their own bug, not drift worth alerting.
  ADD COLUMN prior_seen_count bigint NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------------------
-- tracking_findings — what is wrong with the tracking, not with the product.
--
-- Separate from `leak_instances` because the subject is different in kind: a leak is
-- about a person or a step, and these are about an event name, a property or a
-- source path. Mixing them would mean every leak query had to remember to exclude
-- them.
-- ---------------------------------------------------------------------------
CREATE TABLE tracking_findings (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,

  kind        text NOT NULL CHECK (kind IN (
                'missing-event',      -- an event that normally arrives has stopped
                'shape-drift',        -- a property changed type, or a new one appeared
                'double-sent',        -- two source paths sending the same event
                'late-events',        -- a source arriving consistently late
                'source-share'        -- browser events collapsed against server
              )),
  -- The event name, or `name.property`, or the source path. What the finding is about.
  subject     text NOT NULL,

  /*
   * What makes this one episode.
   *
   * Same idea as a leak's episode key and for the same reason: the sweep runs every
   * few minutes and must not produce a new finding each time. Derived from the facts
   * — the day the event went quiet, the type it changed to — so a genuinely new
   * episode produces a different key.
   */
  episode_key text NOT NULL,

  -- When it became true, not when the sweep noticed.
  detected_at timestamptz NOT NULL,
  -- Set when it stopped being true: the event came back, the property settled.
  resolved_at timestamptz,

  /*
   * The sentence a founder reads, and it says TRACKING, not "users vanished".
   *
   * Brief §9: "The alert says tracking broke, not that users vanished." That is the
   * whole point of this table existing: a Signed Up that stops arriving looks exactly
   * like nobody signing up, and telling a founder their signups went to zero when
   * really their deploy broke the snippet is the fastest way to lose their trust.
   */
  says        text NOT NULL,
  -- What to do about it, in their words.
  fix         text NOT NULL DEFAULT '',
  details     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),

  UNIQUE (project_id, kind, subject, episode_key)
);

CREATE INDEX tracking_findings_open_idx
  ON tracking_findings (project_id, detected_at DESC) WHERE resolved_at IS NULL;

-- ---------------------------------------------------------------------------
-- A tracking alert has no leak instance, so it needs its own dedupe key.
--
-- `alerts`' unique key is (project_id, leak_instance_id), and in Postgres two NULLs
-- are distinct — so every sweep would insert another copy of the same tracking
-- alert. A partial unique index on a key that is only set for these rows fixes it
-- without touching the leak path.
-- ---------------------------------------------------------------------------
ALTER TABLE alerts ADD COLUMN dedupe_key text;
CREATE UNIQUE INDEX alerts_dedupe_key_idx ON alerts (project_id, dedupe_key)
  WHERE dedupe_key IS NOT NULL;

-- A tracking alert is about an event name, not a person or a step.
ALTER TABLE alerts DROP CONSTRAINT alerts_subject_kind_check;
ALTER TABLE alerts ADD CONSTRAINT alerts_subject_kind_check
  CHECK (subject_kind IN ('user', 'account', 'step', 'tracking'));

-- ---------------------------------------------------------------------------
-- retention_runs — what the nightly job deleted, and when.
--
-- Brief §10: "A nightly job writes the day's summaries, then deletes raw events past
-- the window." The order is the requirement, so the record keeps both halves: a run
-- that deleted events without writing summaries first is a bug worth being able to
-- see after the fact.
-- ---------------------------------------------------------------------------
CREATE TABLE retention_runs (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- The founder's own local date, like `report_runs`: "nightly" is their night.
  period_key  text NOT NULL,
  retention_days integer NOT NULL,
  -- Events older than this were deleted.
  cutoff_at   timestamptz NOT NULL,
  summaries_written integer NOT NULL DEFAULT 0,
  events_deleted bigint NOT NULL DEFAULT 0,
  -- Batches, so a long run is visible as progress rather than as a hang.
  batches     integer NOT NULL DEFAULT 0,
  ran_at      timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  UNIQUE (project_id, period_key)
);

ALTER TABLE tracking_findings ENABLE ROW LEVEL SECURITY;
ALTER TABLE tracking_findings FORCE ROW LEVEL SECURITY;
CREATE POLICY tracking_findings_scoped ON tracking_findings
  USING (project_id = app_current_project_id())
  WITH CHECK (project_id = app_current_project_id());
CREATE POLICY tracking_findings_bypass ON tracking_findings
  USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed());

ALTER TABLE retention_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE retention_runs FORCE ROW LEVEL SECURITY;
CREATE POLICY retention_runs_scoped ON retention_runs
  USING (project_id = app_current_project_id())
  WITH CHECK (project_id = app_current_project_id());
CREATE POLICY retention_runs_bypass ON retention_runs
  USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed());

