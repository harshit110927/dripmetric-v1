-- 0009_alerts.sql — M10. Alerts, the delivery log and the reports (brief §9).
--
-- Four things live here, and each one exists because of a specific sentence:
--
--   integrations          "Store those URLs encrypted."
--   alerts                "always to the in-app feed, which has an unread badge"
--   alert_deliveries      "Delivery retries with backoff and keeps a delivery log."
--   report_subscriptions  "with a one-click unsubscribe"
--   report_runs           Monday morning, once — in the founder's time zone.

-- ---------------------------------------------------------------------------
-- integrations — the founder's chat app.
--
-- The webhook URL is a bearer credential: anyone holding it can post into the
-- founder's channel. So it is stored the same way an end-user email is, through
-- app-level AES-256-GCM with the key id beside the ciphertext (settled decision D4),
-- and never in a column anything can read by accident.
-- ---------------------------------------------------------------------------
CREATE TABLE integrations (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('slack', 'discord')),

  -- `<iv><tag><ciphertext>`, and which key wrote it.
  webhook_ciphertext bytea NOT NULL,
  webhook_key_id     text NOT NULL,

  /*
   * What the founder picked, in their words: "#leaks", "Acme HQ · #general".
   *
   * Plain text on purpose. It is the founder's own channel name, not an end user's
   * anything, and the settings screen has to be able to say which channel we post to
   * without decrypting a credential to find out.
   */
  channel_label text NOT NULL DEFAULT '',
  workspace_label text NOT NULL DEFAULT '',

  installed_by uuid REFERENCES founder_users (id) ON DELETE SET NULL,
  installed_at timestamptz NOT NULL DEFAULT now(),
  -- Set when the founder disconnects, or when the webhook answers 404/410 (the
  -- channel or the app is gone). Kept rather than deleted so the delivery log's
  -- foreign key still resolves.
  revoked_at  timestamptz,
  revoked_reason text,

  -- The last thing the channel said back, for the settings screen.
  last_delivery_at timestamptz,
  last_error  text
);

-- One live integration per kind per project. A second install of the same app
-- replaces the first rather than doubling every alert.
CREATE UNIQUE INDEX integrations_live_idx ON integrations (project_id, kind)
  WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- integration_installs — the OAuth `state` nonce.
--
-- A row per install attempt, so the callback can prove the redirect belongs to a
-- flow this project started. In a table rather than a cookie because the callback
-- arrives from Slack's or Discord's domain: a cookie would depend on SameSite
-- behaviour we do not control, and a replayed `code` must fail even if the browser
-- sent nothing.
-- ---------------------------------------------------------------------------
CREATE TABLE integration_installs (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('slack', 'discord')),
  -- Only the hash. The state itself lives in the redirect URL, which is a URL, which
  -- ends up in logs and in browser history.
  state_hash  bytea NOT NULL,
  started_by  uuid REFERENCES founder_users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  -- Single use: set on the callback, and a second callback with the same state is
  -- refused.
  used_at     timestamptz
);
CREATE UNIQUE INDEX integration_installs_state_idx ON integration_installs (state_hash);

-- ---------------------------------------------------------------------------
-- alerts — the in-app feed (brief §9: "always to the in-app feed, which has an
-- unread badge that updates live").
--
-- Every alert lands here whatever happens to the channel post: over the cap, in
-- quiet hours, no app connected, the webhook down. The feed is the record; a channel
-- is a convenience on top of it.
--
-- `title`, `says` and `fields` are STORED rather than regenerated from the leak.
-- A founder reading the feed next week must see what was sent, not what the same
-- leak would say today against a moved threshold.
-- ---------------------------------------------------------------------------
CREATE TABLE alerts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- Null for an alert that is not about a single leak (a tracking-health warning).
  leak_instance_id bigint REFERENCES leak_instances (id) ON DELETE SET NULL,
  leak_type   text NOT NULL,
  subject_kind text NOT NULL CHECK (subject_kind IN ('user', 'account', 'step')),
  subject_key integer NOT NULL,

  title       text NOT NULL,
  says        text NOT NULL,
  -- The label/value pairs the channel post showed, so the feed matches it exactly.
  fields      jsonb NOT NULL DEFAULT '[]'::jsonb,
  /*
   * Whether this alert's text is masked.
   *
   * Not a permission — the serializer decided that already — but a record of what
   * was sent. A project that upgrades later must not retroactively unmask alerts
   * whose channel posts said "User A7F2C1", or the feed and the founder's Slack
   * history would disagree.
   */
  masked      boolean NOT NULL DEFAULT true,

  -- When the leak fired, not when the alert was made.
  fired_at    timestamptz NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  read_at     timestamptz,

  -- 'send' | 'hold' | 'feed-only' | 'drop', from the alert policy, with its reason.
  route       text NOT NULL CHECK (route IN ('send', 'hold', 'feed-only')),
  because     text NOT NULL DEFAULT '',

  -- One alert per leak instance, ever. The sweep runs every five minutes and will
  -- happily offer the same open leak each time; this is what makes that harmless.
  UNIQUE (project_id, leak_instance_id)
);

CREATE INDEX alerts_feed_idx ON alerts (project_id, created_at DESC);
-- The unread badge: a count, from an index that only holds the unread ones.
CREATE INDEX alerts_unread_idx ON alerts (project_id, created_at DESC) WHERE read_at IS NULL;

-- ---------------------------------------------------------------------------
-- alert_deliveries — the delivery log (brief §9: "Delivery retries with backoff and
-- keeps a delivery log").
--
-- A row per alert per channel. The retry state lives here rather than in the queue
-- so that "what happened to Tuesday's alerts" is a question the database answers,
-- including for the attempts that failed.
-- ---------------------------------------------------------------------------
CREATE TABLE alert_deliveries (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  alert_id    bigint NOT NULL REFERENCES alerts (id) ON DELETE CASCADE,
  channel     text NOT NULL CHECK (channel IN ('slack', 'discord', 'email')),
  integration_id bigint REFERENCES integrations (id) ON DELETE SET NULL,

  state       text NOT NULL DEFAULT 'pending'
              CHECK (state IN ('pending', 'held', 'sent', 'failed', 'skipped')),
  -- When this post is due: now for a normal alert, the morning for a held one.
  due_at      timestamptz NOT NULL,
  attempts    integer NOT NULL DEFAULT 0,
  last_attempt_at timestamptz,
  sent_at     timestamptz,
  -- The channel's own words, truncated. Kept for 'failed' and for a 'sent' that
  -- complained.
  last_error  text,
  -- Why it was skipped, when it was.
  because     text,
  created_at  timestamptz NOT NULL DEFAULT now(),

  -- One delivery per alert per channel. A retry updates this row; it does not add one.
  UNIQUE (alert_id, channel)
);

-- The dispatcher's own query: what is due, oldest first.
CREATE INDEX alert_deliveries_due_idx ON alert_deliveries (project_id, due_at)
  WHERE state IN ('pending', 'held');
-- The daily cap counts sent channel posts, by the time they were sent.
CREATE INDEX alert_deliveries_sent_idx ON alert_deliveries (project_id, sent_at)
  WHERE state = 'sent';

-- ---------------------------------------------------------------------------
-- report_subscriptions — who gets the weekly report and the daily digest, and the
-- one-click unsubscribe token (brief §9).
--
-- Per founder per project, not per project: two co-founders on one project may make
-- different choices, and one of them unsubscribing must not silence the other.
-- ---------------------------------------------------------------------------
CREATE TABLE report_subscriptions (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_id     uuid NOT NULL REFERENCES founder_users (id) ON DELETE CASCADE,
  weekly_report boolean NOT NULL DEFAULT true,
  daily_digest  boolean NOT NULL DEFAULT true,
  -- Only the hash. The token itself is in the unsubscribe link, which lives in an
  -- email, which lives on someone else's server.
  unsubscribe_token_hash bytea NOT NULL,
  unsubscribed_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);
CREATE UNIQUE INDEX report_subscriptions_token_idx
  ON report_subscriptions (unsubscribe_token_hash);

-- ---------------------------------------------------------------------------
-- report_runs — what was sent, and when.
--
-- The Monday job is a sweep: it runs hourly and asks each project whether it is
-- Monday morning there yet. That makes "has this week's report gone out?" the thing
-- that stops a founder in Auckland getting two, so it is a unique index rather than
-- a flag in memory.
-- ---------------------------------------------------------------------------
CREATE TABLE report_runs (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('weekly', 'digest')),
  /*
   * The period this run covers, as the founder's own local date.
   *
   * A date rather than a timestamp, and local rather than UTC, because that is what
   * "once a week" and "once a day" mean to them. `2026-11-02` is the Monday the
   * report is for, whatever hour it actually left.
   */
  period_key  text NOT NULL,
  sent_at     timestamptz NOT NULL DEFAULT now(),
  recipients  integer NOT NULL DEFAULT 0,
  -- The subject line, so a founder's support question can be answered.
  subject     text NOT NULL DEFAULT '',
  -- Set when the run decided there was nothing worth sending.
  skipped_because text,
  UNIQUE (project_id, kind, period_key)
);

