-- 0007_leaks.sql — M8. Leak instances (brief §8.3, brief §4's `leak_instances`).
--
-- "One alert per person per leak. A leak fires once per user (or account) per
-- episode. A user who comes back resets it, so a later episode can fire again. The
-- unique key on `leak_instances` is the guarantee."
--
-- That last sentence is why this table exists at all. The rules are pure functions
-- that happily return the same finding on every sweep; what stops a founder getting
-- the same alert every five minutes is the unique index below, not care in the
-- caller.

CREATE TABLE leak_instances (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,

  -- A person, a company, or a step of the funnel. The step-collapse leak is the only
  -- one about a step, and the only unmasked one (brief §8.3).
  subject_kind text NOT NULL CHECK (subject_kind IN ('user', 'account', 'step')),
  subject_key  integer NOT NULL,
  leak_type    text NOT NULL,

  /*
   * What makes this one episode rather than another.
   *
   * Derived from the facts by the engine — the checkout's timestamp, the step entry
   * they went quiet on, the trial's end date — so the same episode produces the same
   * key however often the sweep runs, and a new episode produces a different one.
   * Text rather than a number because it is self-describing: a row says which
   * checkout or which trial it is about, which an integer could not.
   */
  episode_key  text NOT NULL,
  -- How many episodes of this leak this subject has had, for "the third time this
  -- has happened". Display only; the key above is the guarantee.
  episode      integer NOT NULL DEFAULT 1,

  -- When the leak became true, not when a sweep noticed. A sweep that runs late must
  -- not move the time a founder is shown.
  fired_at    timestamptz NOT NULL,
  state       text NOT NULL DEFAULT 'open'
              CHECK (state IN ('open', 'resolved', 'suppressed')),
  -- Set when the thing stopped being true: they came back, or they paid.
  resolved_at timestamptz,

  -- The sentence the founder reads, stored rather than regenerated, so an alert that
  -- was sent and the row behind it can never disagree.
  says        text NOT NULL,
  -- The numbers behind it, so a screen can show its working.
  details     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),

  -- The guarantee (brief §8.3).
  UNIQUE (project_id, subject_kind, subject_key, leak_type, episode_key)
);

-- The dashboard asks "this week's leaks by type"; the weekly report asks the same
-- over seven days.
CREATE INDEX leak_instances_type_idx ON leak_instances (project_id, leak_type, fired_at DESC);
CREATE INDEX leak_instances_subject_idx
  ON leak_instances (project_id, subject_kind, subject_key, fired_at DESC);
-- The alert queue (M10) wants the ones that have not been sent yet.
CREATE INDEX leak_instances_open_idx ON leak_instances (project_id, fired_at DESC)
  WHERE state = 'open';

ALTER TABLE leak_instances ENABLE ROW LEVEL SECURITY;
ALTER TABLE leak_instances FORCE ROW LEVEL SECURITY;
CREATE POLICY leak_instances_scoped ON leak_instances
  USING (project_id = app_current_project_id())
  WITH CHECK (project_id = app_current_project_id());
CREATE POLICY leak_instances_bypass ON leak_instances
  USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed());

