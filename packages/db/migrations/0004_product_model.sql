-- 0004_product_model.sql — M5. The product model and event matching (brief §7).
--
-- Every product's raw events are translated into one canonical vocabulary, so the
-- same funnel, leak and intent logic runs for all of them. Translation happens once
-- per product at setup, with AI suggestions the founder confirms, and anything
-- unmapped waits in an Inbox instead of skewing metrics.

-- ---------------------------------------------------------------------------
-- The five product facts (brief §2).
--
-- "Each project ends setup with five facts the founder confirms, pre-filled from the
-- first 100 events where possible." They live on `projects.settings` already, except
-- the funnel (which is `funnels` + `funnel_steps`). What is missing is the record of
-- WHICH have been confirmed, because setup is not finished until they all are, and
-- the paid event is required to finish it (settled decision 9).
-- ---------------------------------------------------------------------------
CREATE TABLE product_facts (
  project_id  integer PRIMARY KEY REFERENCES projects (id) ON DELETE CASCADE,
  -- Each is null until the founder confirms it; the value itself lives in
  -- settings or the funnel tables.
  steps_confirmed_at      timestamptz,
  activation_confirmed_at timestamptz,
  paid_event_confirmed_at timestamptz,
  price_confirmed_at      timestamptz,
  trial_confirmed_at      timestamptz,
  -- Set when all five are in. Until then the dashboard shows what it can and says
  -- plainly what is missing.
  setup_completed_at      timestamptz,
  -- The AI suggestion run: when it last happened and what it cost, so a founder's
  -- bill is never a surprise to us either.
  suggestions_run_at      timestamptz,
  suggestions_input_tokens  integer,
  suggestions_output_tokens integer,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- The property keys and shape-only samples we show the model (brief §7).
--
-- "Input: the distinct raw event names (top 60 by volume), their property keys,
-- shape-only samples (the type, and a value only when the property has few distinct
-- short values), typical position in user sequences."
--
-- Kept as its own table rather than computed on demand, because the scrubber has to
-- run over it ONCE, where it can be tested, rather than every time a prompt is built.
-- ---------------------------------------------------------------------------
CREATE TABLE event_name_properties (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  name_id     integer NOT NULL,
  property    text NOT NULL,
  -- 'string' | 'number' | 'boolean' | 'object' | 'array' | 'null'
  value_type  text NOT NULL,
  -- A sample only when the property has few distinct short values, e.g. a plan name
  -- or a step label. Never an id, an email or free text. Always post-scrub.
  sample      text,
  distinct_values integer NOT NULL DEFAULT 0,
  seen_count  bigint NOT NULL DEFAULT 0,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, name_id, property),
  FOREIGN KEY (project_id, name_id) REFERENCES event_names (project_id, id) ON DELETE CASCADE
);

-- Where this name usually falls in a user's sequence, which is most of what tells
-- "Signed Up" from "Subscription Started" when the names are the founder's own.
ALTER TABLE event_names
  ADD COLUMN median_sequence_position numeric,
  -- How many distinct people have ever sent it: a name one person sent once is not
  -- a core action, whatever it is called.
  ADD COLUMN distinct_users integer NOT NULL DEFAULT 0,
  -- Who confirmed the mapping and when, so the audit log can explain a number.
  ADD COLUMN confirmed_by uuid REFERENCES founder_users (id) ON DELETE SET NULL,
  ADD COLUMN confirmed_at timestamptz;

-- ---------------------------------------------------------------------------
-- The recompute job (brief §7, CLAUDE.md rule 10).
--
-- "Changing a mapping, a URL rule or a funnel step triggers the idempotent
-- `recompute` job for the project, in chunks that can resume."
--
-- The chunk cursor lives here so a run that dies halfway resumes rather than
-- restarting, which matters because a project with 13 months of events is not a
-- single transaction.
-- ---------------------------------------------------------------------------
CREATE TABLE recompute_runs (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- Why it was triggered, so a founder asking "why did my numbers change?" has an
  -- answer: 'mapping' | 'url-rule' | 'funnel' | 'manual' | 'settings'.
  reason      text NOT NULL,
  state       text NOT NULL DEFAULT 'pending'
              CHECK (state IN ('pending', 'running', 'done', 'failed')),
  -- The resume cursor: events are walked in (occurred_at, message_hash) order.
  cursor_occurred_at timestamptz,
  cursor_message_hash uuid,
  events_seen  bigint NOT NULL DEFAULT 0,
  started_at   timestamptz,
  finished_at  timestamptz,
  error        text,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX recompute_runs_project_idx ON recompute_runs (project_id, created_at DESC);
-- One run at a time per project: a second would rebuild the same rows from the same
-- events and race the first.
CREATE UNIQUE INDEX recompute_runs_one_active
  ON recompute_runs (project_id)
  WHERE state IN ('pending', 'running');

-- ---------------------------------------------------------------------------
-- Row-level security, same rules as everywhere else.
-- ---------------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['product_facts', 'event_name_properties', 'recompute_runs'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (project_id = app_current_project_id()) WITH CHECK (project_id = app_current_project_id())',
      t || '_scoped', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed())',
      t || '_bypass', t);
  END LOOP;
END
$$;

