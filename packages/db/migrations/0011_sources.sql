-- 0011_sources.sql — M12. The no-code source feeds (brief §5).
--
-- Segment, RudderStack and PostHog each post to a URL we give the founder. That URL
-- has to identify the project without being guessable, and the delivery has to prove
-- it came from the tool — so a source is a row with a public id and a shared secret.

CREATE TABLE sources (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('segment', 'rudderstack', 'posthog')),

  /*
   * The id in the webhook URL. A uuid, not the project's own public id.
   *
   * It appears in a third party's configuration screen and in their logs, so it is a
   * separate identifier that can be rotated without touching the project — and one
   * leaked source URL does not reveal the project it belongs to.
   */
  public_id   uuid NOT NULL DEFAULT gen_random_uuid(),

  -- The shared secret, encrypted like every other credential (settled decision D4).
  secret_ciphertext bytea NOT NULL,
  secret_key_id     text NOT NULL,

  /*
   * Which ingest key the adapter posts with.
   *
   * The adapter goes in through the real `/v1/batch` entry point rather than calling
   * the pipeline directly, so a no-code feed is rate-limited, authenticated and
   * audited exactly like an SDK one. This is the key it uses — the project's own
   * secret key, so events are correctly treated as server-sent.
   */
  api_key_id  uuid REFERENCES api_keys (id) ON DELETE SET NULL,

  created_by  uuid REFERENCES founder_users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  revoked_at  timestamptz,

  -- What the last delivery did, for the settings screen and for M11's health view.
  last_delivery_at timestamptz,
  last_ok_at  timestamptz,
  last_error  text,
  deliveries  bigint NOT NULL DEFAULT 0,
  accepted    bigint NOT NULL DEFAULT 0,
  dropped     bigint NOT NULL DEFAULT 0,
  /*
   * What was dropped and why, as a rolling tally.
   *
   * Brief §5: "PostHog events outside the allow-list are dropped and COUNTED". A
   * founder who wires PostHog needs to see that 94% of what it sent was autocapture,
   * or they will assume we lost their data.
   */
  drop_reasons jsonb NOT NULL DEFAULT '{}'::jsonb
);

-- One live source per kind per project: two would double every event.
CREATE UNIQUE INDEX sources_live_idx ON sources (project_id, kind) WHERE revoked_at IS NULL;
CREATE UNIQUE INDEX sources_public_id_idx ON sources (public_id);

ALTER TABLE sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE sources FORCE ROW LEVEL SECURITY;
CREATE POLICY sources_scoped ON sources
  USING (project_id = app_current_project_id())
  WITH CHECK (project_id = app_current_project_id());
CREATE POLICY sources_bypass ON sources
  USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed());

