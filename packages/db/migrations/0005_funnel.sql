-- 0005_funnel.sql — M6. The funnel and timing engine's stored state (brief §8.1).
--
-- The engine is pure: it takes facts and `now` and returns a report. These tables are
-- the facts it is given and the results it produces, so a dashboard read is a SELECT
-- rather than a scan of every event (brief §9: "cache dashboard reads for 60 seconds";
-- a read that needed a scan could not be cached usefully in the first place).
--
-- Everything here is derived state and must be rebuildable from raw events plus
-- settings by an idempotent job (CLAUDE.md rule 10).

-- ---------------------------------------------------------------------------
-- Founder-marked changes (brief §4 `changes`, brief §9's Changes module).
--
-- "Thresholds freeze when the founder marks a change, so a before-and-after
-- comparison is not measured against a moving bar." The frozen numbers live on the
-- change itself, not on the step, because the step's own thresholds keep moving and
-- the whole point is to hold one copy still.
-- ---------------------------------------------------------------------------
CREATE TABLE changes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- Null means "the whole funnel", which is what a pricing change or a new landing
  -- page is.
  step_id     integer,
  -- When the founder says the change went live, not when they told us.
  happened_at timestamptz NOT NULL,
  note        text NOT NULL,
  -- Every step's thresholds as they stood at `happened_at`. The shape is the
  -- engine's `FrozenThresholds.thresholds`.
  frozen_thresholds jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- The before-and-after result, frozen once the after window has passed (M10).
  result      jsonb,
  created_by  uuid REFERENCES founder_users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE SET NULL
);
CREATE INDEX changes_project_idx ON changes (project_id, happened_at DESC);

-- ---------------------------------------------------------------------------
-- The thresholds in force for each step (brief §8.1).
--
-- "Every threshold is a percentile of the product's own users, so a 6-minute data
-- import and a 20-second profile step are each judged against their own history."
--
-- Stored rather than computed per read for two reasons: a percentile needs every
-- completion of that step, and a threshold that moved while the founder was reading
-- the screen would make "stuck now" mean something different each time they looked.
-- ---------------------------------------------------------------------------
CREATE TABLE step_thresholds (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  step_id     integer NOT NULL,
  -- How many completions the percentiles were computed from. Below 20 the engine
  -- shows no percentile at all (brief §8.1).
  completions integer NOT NULL DEFAULT 0,
  -- p10 of elapsed: faster than this is a candidate for "skimmed".
  rushed_seconds        numeric,
  -- p90 of active time on the step.
  stuck_active_seconds  numeric,
  -- p90 of elapsed, clamped to 1–72 hours. Never null: a default applies.
  stuck_elapsed_seconds numeric NOT NULL,
  -- p90 of the gap to the next step: longer than this is "cooling".
  cooling_gap_seconds   numeric,
  computed_at timestamptz NOT NULL,
  -- Set while frozen by a marked change. A frozen row is never recomputed.
  frozen_by_change_id bigint REFERENCES changes (id) ON DELETE SET NULL,
  PRIMARY KEY (project_id, step_id),
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Which sessions each person spent on each step (brief §8.1: "visits (separate
-- sessions spent on the step)").
--
-- Until now `visits` was an accumulating counter, and it could only count the
-- distinct sessions inside ONE batch: a visitor who came back in a later batch was
-- counted again as a first visit, so the number undercounted every returning user.
-- The simulator found it; the fix needs the sessions themselves.
--
-- It earns its keep twice. `visits` becomes an absolute recount, which is idempotent
-- and order-insensitive like everything else in the derived state. And the segment
-- splits attribute a step to the session the person was actually in, so someone who
-- starts a step on a phone and finishes it on a laptop is counted where they were —
-- which is exactly the case the splits exist to find.
--
-- About 16 bytes a row, and a row only exists for a (person, step, session) that
-- really happened.
-- ---------------------------------------------------------------------------
CREATE TABLE user_step_sessions (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_key    integer NOT NULL,
  step_id     integer NOT NULL,
  session_id  bigint NOT NULL,
  PRIMARY KEY (project_id, user_key, step_id, session_id),
  FOREIGN KEY (project_id, user_key) REFERENCES end_users (project_id, user_key) ON DELETE CASCADE,
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE,
  FOREIGN KEY (project_id, session_id) REFERENCES sessions (project_id, id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Hourly and daily aggregates per step (brief §11, M6).
--
-- A person is counted on the hour and day they ENTERED the step, and again on the
-- hour and day they COMPLETED it, which are often different. That is what makes an
-- 8-week trend per step readable: each week says how many started and how many of
-- the people who started got through.
-- ---------------------------------------------------------------------------
CREATE TABLE step_hourly (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  step_id     integer NOT NULL,
  -- Truncated to the hour, UTC.
  hour        timestamptz NOT NULL,
  entered     integer NOT NULL DEFAULT 0,
  completed   integer NOT NULL DEFAULT 0,
  PRIMARY KEY (project_id, step_id, hour),
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE
);

CREATE TABLE step_daily (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  step_id     integer NOT NULL,
  day         date NOT NULL,
  entered     integer NOT NULL DEFAULT 0,
  completed   integer NOT NULL DEFAULT 0,
  -- "Users who entered, completed and are stuck now" (brief §8.1). Stuck is a
  -- present tense, so a daily row records how many were stuck when the day ended.
  stuck_at_end integer NOT NULL DEFAULT 0,
  -- The elapsed-time distribution for the people who completed on this day. Kept so
  -- a trend does not have to rescan, and nullable because percentiles are withheld
  -- below 20 completions.
  completions integer NOT NULL DEFAULT 0,
  avg_seconds numeric,
  p10_seconds numeric,
  p25_seconds numeric,
  p50_seconds numeric,
  p75_seconds numeric,
  p90_seconds numeric,
  PRIMARY KEY (project_id, step_id, day),
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Segment splits (brief §8.1).
--
-- "Segment splits (device, browser, operating system, country, channel, campaign) on
-- every step. A step that 70% of users complete on Chrome desktop but 20% on Safari
-- for iPhone is a bug, not low intent: say so."
--
-- The dimension's value is the session's own context, stored once per session
-- already. The cardinality is bounded by what a browser can report, except for
-- campaign, which is bounded by what the founder runs.
-- ---------------------------------------------------------------------------
CREATE TABLE step_segment_daily (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  step_id     integer NOT NULL,
  day         date NOT NULL,
  dimension   text NOT NULL
              CHECK (dimension IN ('device', 'browser', 'os', 'country', 'channel', 'campaign')),
  -- Null is a real answer ("no campaign") and is shown as "none".
  value       text,
  entered     integer NOT NULL DEFAULT 0,
  completed   integer NOT NULL DEFAULT 0,
  -- A null value cannot take part in a primary key, so the key uses a coalesced
  -- expression and the raw value is kept beside it for display.
  value_key   text NOT NULL GENERATED ALWAYS AS (coalesce(value, '')) STORED,
  PRIMARY KEY (project_id, step_id, day, dimension, value_key),
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Retention cohorts (brief §9's Retention module).
--
-- "Free shows week-1 and week-4 retention; paid adds the full signup-week cohort
-- table." The whole table is computed either way — it is the same scan — and the
-- entitlement decides what is shown.
-- ---------------------------------------------------------------------------
CREATE TABLE retention_cohorts (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- The Monday of the signup week, UTC.
  cohort_week date NOT NULL,
  users       integer NOT NULL DEFAULT 0,
  -- Week offset to the number retained: {"1": 14, "4": 6}.
  retained    jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Null until the week has fully passed: a cohort that signed up yesterday has not
  -- failed week 4, it has not reached it.
  week1_rate  numeric,
  week4_rate  numeric,
  complete_weeks integer NOT NULL DEFAULT 0,
  computed_at timestamptz NOT NULL,
  PRIMARY KEY (project_id, cohort_week)
);

-- ---------------------------------------------------------------------------
-- Daily summaries (brief §4): "Per project and day: funnel per step, event counts,
-- intent per band, leak counts, weekly retention cohorts. Kept forever, about 1 MB
-- per project per year."
--
-- One JSONB payload rather than a column per number, because the retention job
-- deletes raw events and these have to survive it — and because M7 and M8 add their
-- own sections to the same row without a migration each.
-- ---------------------------------------------------------------------------
CREATE TABLE daily_summaries (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  day         date NOT NULL,
  -- { funnel: [...], events: {...}, intent: {...}, leaks: {...}, retention: [...] }
  payload     jsonb NOT NULL DEFAULT '{}'::jsonb,
  computed_at timestamptz NOT NULL,
  PRIMARY KEY (project_id, day)
);

-- ---------------------------------------------------------------------------
-- Row-level security, same rules as everywhere else.
-- ---------------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['changes', 'step_thresholds', 'user_step_sessions',
                           'step_hourly', 'step_daily', 'step_segment_daily',
                           'retention_cohorts', 'daily_summaries'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (project_id = app_current_project_id()) WITH CHECK (project_id = app_current_project_id())',
      t || '_scoped', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed())',
      t || '_bypass', t);
  END LOOP;
END
$$;

